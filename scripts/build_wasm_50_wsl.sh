#!/usr/bin/env bash
# NetHack 5.0 WebAssembly Build Script for WSL2 (Ubuntu)
# Linux Native Build - Bypasses Windows Smart App Control Binaryen blocks

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DEPLOY_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
NH_ROOT="${1:-/mnt/c/Users/e3-sh/Desktop/works/NetHack-NetHack-5.0_org/NetHack-NetHack-5.0.1_Oct16_2026}"
EMSDK_PATH="${2:-$HOME/emsdk}"
LUA_SOURCE_FALLBACK="/mnt/c/Users/e3-sh/Documents/Antigravity/NetHack/lib/lua-5.4.8"

echo "=== NetHack 5.0 WASM Linux Native Build (WSL2) ==="
echo "NetHack Root: $NH_ROOT"
echo "Deploy Root : $DEPLOY_ROOT"
echo "EMSDK Path  : $EMSDK_PATH"

if [ ! -d "$NH_ROOT" ]; then
    echo "Error: NetHack root not found at $NH_ROOT" >&2
    exit 1
fi

# 1. Activate Emscripten
echo "--- Step 1: Activating Emscripten SDK ---"
if [ -f "$EMSDK_PATH/emsdk_env.sh" ]; then
    # shellcheck disable=SC1090
    source "$EMSDK_PATH/emsdk_env.sh"
else
    echo "Error: Emscripten SDK not found at $EMSDK_PATH/emsdk_env.sh" >&2
    exit 1
fi

emcc --version

cd "$NH_ROOT"

# 2. Prepare Lua source & Generate nhlua.h
LUA_SRC_DIR="nhlua/lua/src"
if [ ! -d "$LUA_SRC_DIR" ]; then
    LUA_VERSION="5.4.8"
    LUA_SRC_DIR="lib/lua-$LUA_VERSION/src"
    if [ ! -d "$LUA_SRC_DIR" ]; then
        if [ -d "$LUA_SOURCE_FALLBACK" ]; then
            echo "Preparing Lua source from $LUA_SOURCE_FALLBACK..."
            mkdir -p "lib"
            cp -r "$LUA_SOURCE_FALLBACK" "lib/lua-$LUA_VERSION"
        else
            echo "Error: Lua source not found." >&2
            exit 1
        fi
    fi
fi
echo "Using Lua source: $LUA_SRC_DIR"

echo "--- Generating include/nhlua.h ---"
cat << 'EOF' > include/nhlua.h
/* nhlua.h - generated by build_wasm_50_wsl.sh */
#include "lua.h"
#include "lualib.h"
#include "lauxlib.h"
/*nhlua.h*/
EOF

# 3. Build Host Utilities (makedefs & tilemap) with gcc
echo "--- Step 2: Building makedefs & tilemap (Host GCC) ---"
gcc -O2 -Iinclude -I"$LUA_SRC_DIR" -DCROSSCOMPILE \
    util/makedefs.c src/monst.c src/objects.c src/alloc.c util/panic.c src/hacklib.c src/date.c \
    -o util/makedefs

if [ ! -f "src/tile.c" ]; then
    echo "Building and running tilemap..."
    gcc -O2 -Iinclude -I"$LUA_SRC_DIR" -DCROSSCOMPILE \
        win/share/tilemap.c src/monst.c src/objects.c src/drawing.c src/hacklib.c util/panic.c src/alloc.c \
        -o util/tilemap
    (cd util && ./tilemap)
else
    echo "src/tile.c already exists. Skipping tilemap build."
fi

# 4. Generate data files
echo "--- Step 3: Generating NetHack data files with makedefs ---"
(cd util && ./makedefs -d)
(cd util && ./makedefs -r)
(cd util && ./makedefs -h)
(cd util && ./makedefs -s)
(cd util && ./makedefs -o)

# 5. Sync shim_bridge.c from WebUI repo
echo "--- Step 4: Syncing shim_bridge.c ---"
if [ -f "$DEPLOY_ROOT/src/driver/shim/shim_bridge.c" ]; then
    cp "$DEPLOY_ROOT/src/driver/shim/shim_bridge.c" "win/shim/shim_bridge.c"
    echo "Synced win/shim/shim_bridge.c from WebUI repo."
else
    echo "Error: shim_bridge.c not found in WebUI repo." >&2
    exit 1
fi

# 6. Build Wasm Lua library
echo "--- Step 5: Building Lua (Wasm) ---"
rm -f *.o liblua.a
LUA_FILES=$(find "$LUA_SRC_DIR" -maxdepth 1 -name "*.c" ! -name "lua.c" ! -name "luac.c")
# shellcheck disable=SC2086
emcc -O3 -c $LUA_FILES -I"$LUA_SRC_DIR"
emar r liblua.a ./*.o
emar s liblua.a
rm -f ./*.o

# 7. Build NetHack Wasm
echo "--- Step 6: Compiling and Linking NetHack Wasm ---"
NETHACK_SRC=(
    "src/allmain.c" "src/alloc.c" "src/apply.c" "src/artifact.c" "src/attrib.c"
    "src/ball.c" "src/bones.c" "src/botl.c" "src/calendar.c" "src/cfgfiles.c" "src/coloratt.c"
    "src/cmd.c" "src/date.c" "src/dbridge.c" "src/decl.c" "src/detect.c" "src/dig.c"
    "src/display.c" "src/dlb.c" "src/do.c" "src/do_name.c" "src/do_wear.c"
    "src/dog.c" "src/dogmove.c" "src/dokick.c" "src/dothrow.c" "src/drawing.c"
    "src/dungeon.c" "src/earlyarg.c" "src/eat.c" "src/end.c" "src/engrave.c"
    "src/exper.c" "src/explode.c" "src/extralev.c" "src/files.c" "src/fountain.c"
    "src/getpos.c" "src/glyphs.c" "src/hack.c" "src/hacklib.c" "src/iactions.c"
    "src/insight.c" "src/invent.c" "src/isaac64.c" "src/light.c" "src/lock.c"
    "src/mail.c" "src/makemon.c" "src/mcastu.c" "src/mdlib.c" "src/mhitm.c"
    "src/mhitu.c" "src/minion.c" "src/mklev.c" "src/mkmap.c" "src/mkmaze.c"
    "src/mkobj.c" "src/mkroom.c" "src/mon.c" "src/mondata.c" "src/monmove.c"
    "src/monst.c" "src/mplayer.c" "src/mthrowu.c" "src/muse.c" "src/music.c"
    "src/nhlua.c" "src/nhlsel.c" "src/nhlobj.c" "src/nhmd4.c" "src/objects.c"
    "src/o_init.c" "src/objnam.c" "src/options.c" "src/pager.c" "src/pickup.c"
    "src/pline.c" "src/polyself.c" "src/potion.c" "src/pray.c" "src/priest.c"
    "src/quest.c" "src/questpgr.c" "src/read.c" "src/rect.c" "src/region.c"
    "src/report.c" "src/restore.c" "src/revision.c" "src/rip.c" "src/rnd.c" "src/role.c"
    "src/rumors.c" "src/save.c" "src/selvar.c" "src/sfbase.c" "src/sfstruct.c" "src/shk.c"
    "src/shknam.c" "src/sit.c" "src/sounds.c" "src/sp_lev.c" "src/spell.c"
    "src/stairs.c" "src/steal.c" "src/steed.c" "src/strutil.c" "src/symbols.c" "src/sys.c"
    "src/teleport.c" "src/timeout.c" "src/topten.c" "src/track.c" "src/trap.c"
    "src/u_init.c" "src/uhitm.c" "src/utf8map.c" "src/vault.c" "src/version.c"
    "src/vision.c" "src/weapon.c" "src/were.c" "src/wield.c" "src/windows.c"
    "src/wizard.c" "src/wizcmds.c" "src/worm.c" "src/worn.c" "src/write.c"
    "src/zap.c"
)
WASM_SYS_SRC=(
    "sys/libnh/libnhmain.c"
    "sys/share/ioctl.c"
    "sys/share/unixtty.c"
    "sys/share/pmatchregex.c"
    "sys/unix/unixunix.c"
    "sys/unix/unixres.c"
    "win/shim/winshim.c"
    "win/shim/shim_bridge.c"
)

emcc "${NETHACK_SRC[@]}" "${WASM_SYS_SRC[@]}" "liblua.a" \
    -O2 \
    -Iinclude \
    -I"$LUA_SRC_DIR" \
    -DCROSSCOMPILE \
    -DCROSSCOMPILE_TARGET \
    -DCROSS_TO_WASM \
    -DNOTTYGRAPHICS \
    -DSHIM_GRAPHICS \
    -DLIBNH \
    -DNOMAIL \
    -DNO_SIGNAL \
    -sASYNCIFY=1 \
    -sASYNCIFY_IMPORTS="['local_callback']" \
    -sDYNCALLS=1 \
    -sEXPORTED_FUNCTIONS="['_main','_shim_graphics_set_callback','_malloc','_free','_shim_bridge_call']" \
    -sEXPORTED_RUNTIME_METHODS="['cwrap','ccall','addFunction','UTF8ToString','stringToUTF8','getValue','setValue','FS','IDBFS']" \
    -lidbfs.js \
    -sALLOW_TABLE_GROWTH=1 \
    -sALLOW_MEMORY_GROWTH=1 \
    -sERROR_ON_UNDEFINED_SYMBOLS=0 \
    --embed-file dat@/ \
    -o nethack.js

# 8. Deploy
echo "--- Step 7: Deploying to WebUI Root and Svelte Client ---"
cp nethack.js "$DEPLOY_ROOT/nethack.js"
cp nethack.wasm "$DEPLOY_ROOT/nethack.wasm"

if [ -d "$DEPLOY_ROOT/examples/svelte-client/dist" ]; then
    cp nethack.js "$DEPLOY_ROOT/examples/svelte-client/dist/nethack.js"
    cp nethack.wasm "$DEPLOY_ROOT/examples/svelte-client/dist/nethack.wasm"
    echo "Copied to examples/svelte-client/dist/."
fi

if [ -f "util/tilemappings.lst" ]; then
    cp "util/tilemappings.lst" "$DEPLOY_ROOT/docs/5_gamedata/tilemappings.lst"
elif [ -f "tilemappings.lst" ]; then
    cp "tilemappings.lst" "$DEPLOY_ROOT/docs/5_gamedata/tilemappings.lst"
fi

echo "=== WSL2 Linux Native Build Completed Successfully! ==="
