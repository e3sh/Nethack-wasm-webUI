    "-sDYNCALLS=1",
    "-lidbfs.js",
    "-sALLOW_TABLE_GROWTH=1",
    "-sALLOW_MEMORY_GROWTH=1",
    "-sERROR_ON_UNDEFINED_SYMBOLS=0"
)
$emcc_flags | Out-File -FilePath nethack_flags.rsp -Encoding ascii

# 7. Final Link with embedded files
Write-Host "--- Step 4: Linking and Packaging (nethack_jp.js / nethack_jp.wasm) ---"
Unblock-File "C:\Users\e3-sh\Documents\GitHub\emsdk\upstream\bin\wasm-emscripten-finalize.exe" -ErrorAction SilentlyContinue
cmd /c "emcc @nethack_files.rsp @nethack_flags.rsp -o nethack_jp.js --embed-file dat@/"

# 8. Deploy outputs
Write-Host "--- Step 5: Deploying build outputs ---"
Copy-Item "nethack_jp.js" "$BASE_ROOT/" -Force
Copy-Item "nethack_jp.wasm" "$BASE_ROOT/" -Force

Set-Location $BASE_ROOT

Write-Host "=== NetHackJP Wasm Build Complete! ==="
