# NetHackJP WebAssembly Build Script for Windows
# Compiles satokiyon/NetHackJP to Wasm for WebUI

$ErrorActionPreference = "Stop"

$BASE_ROOT = $PWD
$NH_ROOT = Join-Path $BASE_ROOT "NetHackJP"
$EMSDK_PATH = "C:\Users\e3-sh\Documents\GitHub\emsdk"
$VCVARS_PATH = "C:\Program Files\Microsoft Visual Studio\18\Community\VC\Auxiliary\Build\vcvarsall.bat"

Write-Host "=== Building NetHackJP Wasm ==="

# 1. Setup Environments
Write-Host "--- Setting up environments ---"
if (Test-Path "$EMSDK_PATH\emsdk_env.ps1") {
    & "$EMSDK_PATH\emsdk_env.ps1"
}
else {
    Write-Error "Emscripten SDK not found at $EMSDK_PATH"
}

if (!(Get-Command cl -ErrorAction SilentlyContinue)) {
    Write-Host "Activating MSVC..."
    $vcvars_cmd = "`"$VCVARS_PATH`" x64 && set"
    $env_vars = cmd /c $vcvars_cmd
    foreach ($line in $env_vars) {
        if ($line -match "^(.*?)=(.*)$") {
            $name = $Matches[1]
            $value = $Matches[2]
            if ($name -ne "" -and $name -notmatch " ") {
                Set-Item "env:$name" $value
            }
        }
    }
}

# 2. Patch winshim.c into NetHackJP
Write-Host "--- Copying winshim.c to NetHackJP/win/shim ---"
$shim_src = Join-Path $BASE_ROOT "NetHack-NetHack-5.0/win/shim/winshim.c"
$shim_dst = Join-Path $NH_ROOT "win/shim/winshim.c"
if (Test-Path $shim_src) {
    if (!(Test-Path (Split-Path $shim_dst))) {
        New-Item -ItemType Directory -Path (Split-Path $shim_dst) -Force
    }
    Copy-Item $shim_src $shim_dst -Force
} else {
    Write-Error "Source winshim.c not found at $shim_src"
}

Set-Location $NH_ROOT

# 3. Generate nhlua.h
Write-Host "--- Generating nhlua.h ---"
$nhlua_content = @"
/* nhlua.h - generated by build_wasm_jp.ps1 */
#include "lua.h"
LUA_API int (lua_error) (lua_State *L) NORETURN;
#include "lualib.h"
#include "lauxlib.h"
/*nhlua.h*/
"@
$nhlua_content | Out-File -FilePath "include/nhlua.h" -Encoding ascii

# 4. Build Host Utilities (makedefs, tilemap) if needed
Write-Host "--- Step 1: Building makedefs (Host) ---"
$LUA_INC = "submodules/lua"
$makedefs_src = @(
    "util/makedefs.c",
    "src/monst.c",
    "src/objects.c",
    "src/alloc.c",
    "util/panic.c",
    "src/hacklib.c",
    "src/date.c",
    "src/mon_jp.c",
    "src/obj_jp.c"
)
cl /utf-8 /O2 /Iinclude /Isys/windows /I$LUA_INC /DCROSSCOMPILE /DWIN32 $makedefs_src /link /out:util/makedefs.exe

Write-Host "--- Step 1-b: Building tilemap (Host) ---"
$tilemap_src = @(
    "win/share/tilemap.c",
    "src/monst.c",
    "src/objects.c",
    "src/drawing.c",
    "src/hacklib.c",
    "util/panic.c",
    "src/alloc.c"
)
cl /utf-8 /O2 /Iinclude /Isys/windows /I$LUA_INC /DCROSSCOMPILE /DWIN32 $tilemap_src /link /out:util/tilemap.exe
if ($LASTEXITCODE -eq 0) {
    Write-Host "Running tilemap.exe to generate tilemappings.lst..."
    Unblock-File util/tilemap.exe -ErrorAction SilentlyContinue
    cmd /c "cd /d `"$NH_ROOT\util`" && tilemap.exe"
    Copy-Item "util/tilemappings.lst" "./" -Force -ErrorAction SilentlyContinue
}

# 5. Generate data files
Write-Host "--- Step 2: Generating data files ---"
if (Test-Path "util/makedefs.exe") {
    Unblock-File util/makedefs.exe -ErrorAction SilentlyContinue
    $util_dir = Join-Path $NH_ROOT "util"
    cmd /c "cd /d `"$util_dir`" && makedefs.exe -d && makedefs.exe -r && makedefs.exe -h && makedefs.exe -s && makedefs.exe -o"
}

# 6. Build NetHackJP Wasm (including Lua sources directly)
Write-Host "--- Step 3: Compiling NetHackJP + Lua (Wasm) ---"
$lua_src = Get-ChildItem "$LUA_INC/*.c" | Where-Object { $_.Name -notmatch "lua.c|luac.c" } | ForEach-Object { "submodules/lua/$($_.Name)" }

