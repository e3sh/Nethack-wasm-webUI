    "-I$LUA_INC",
    "-DCROSSCOMPILE",
    "-DCROSSCOMPILE_TARGET",
    "-DCROSS_TO_WASM",
    "-DNOTTYGRAPHICS",
    "-DSHIM_GRAPHICS",
    "-DLIBNH",
    "-DNOMAIL",
    "-DNO_SIGNAL",
    "-sASYNCIFY=1",
    "-sASYNCIFY_IMPORTS=['local_callback']",
    "-sEXPORTED_FUNCTIONS=['_main','_shim_graphics_set_callback','_repopulate_perminvent','_malloc','_get_plname','_get_nummons','_get_num_objects']",
